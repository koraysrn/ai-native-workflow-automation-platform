import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { test } from "node:test";
import { metricBase, metricTokens } from "../../grafana/lib/metrics.mjs";
import { renderBackendMetrics, renderExporterMetrics } from "../synthetic-metrics.mjs";

const DASHBOARD = new URL("../../grafana/provisioning/dashboards/awap.json", import.meta.url);
const EXPECTATIONS = new URL("../../grafana/query-expectations.json", import.meta.url);
const CATALOG = new URL("../../grafana/metric-catalog.json", import.meta.url);
const CDC_RULES = new URL("../cdc-alert-rules.yml", import.meta.url);
const ALERT_TEST = new URL("./alert-rules.test.yml", import.meta.url);

async function loadJson(url) {
  return JSON.parse(await readFile(url, "utf8"));
}

function expositionNames(text) {
  const names = new Set();
  for (const line of text.split("\n")) {
    if (line.length === 0 || line.startsWith("#")) {
      continue;
    }
    names.add(line.slice(0, line.search(/[{ ]/)));
  }
  return names;
}

test("synthetic exposition is syntactically valid Prometheus text format", () => {
  for (const body of [renderBackendMetrics(3), renderExporterMetrics(3)]) {
    for (const line of body.trim().split("\n")) {
      assert.match(line, /^[a-zA-Z_:][a-zA-Z0-9_:]*(\{[^}]*\})? -?\d+(\.\d+)?$/, line);
    }
  }
});

test("every dashboard query references a metric the synthetic exporter emits", async () => {
  const dashboard = await loadJson(DASHBOARD);
  const emitted = expositionNames(renderBackendMetrics(1));
  const missing = [];
  for (const panel of dashboard.panels) {
    for (const target of panel.targets) {
      for (const token of metricTokens(target.expr)) {
        // `up` is generated by Prometheus itself, not scraped from the exporter.
        if (token === "up") {
          continue;
        }
        if (!emitted.has(token) && !emitted.has(metricBase(token))) {
          missing.push(`${panel.title}: ${token}`);
        }
      }
    }
  }
  assert.deepEqual(missing, [], `synthetic exporter is missing: ${missing.join(", ")}`);
});

test("query expectations declare every provisioned panel", async () => {
  const dashboard = await loadJson(DASHBOARD);
  const expectations = await loadJson(EXPECTATIONS);
  assert.ok(expectations.sentinel?.value, "a sentinel value is required for the empty case");
  assert.equal(expectations.sentinel.expect, "empty");
  assert.deepEqual(
    Object.keys(expectations.panels).sort(),
    dashboard.panels.map((panel) => panel.title).sort(),
  );
});

test("the sentinel value can never match a synthetic series", () => {
  const sentinel = "__awap_no_data__";
  for (const body of [renderBackendMetrics(2), renderExporterMetrics(2)]) {
    assert.ok(!body.includes(sentinel), `synthetic exposition contains the sentinel ${sentinel}`);
  }
});

test("synthetic exporter carries the CDC series the CDC rules depend on", async () => {
  const exporter = renderExporterMetrics(1);
  const cdcRules = await readFile(CDC_RULES, "utf8");
  for (const metric of ["pg_replication_slots_active", "pg_replication_slots_pg_wal_lsn_diff"]) {
    assert.ok(exporter.includes(metric), `synthetic exporter is missing ${metric}`);
    assert.ok(cdcRules.includes(metric), `CDC rules no longer reference ${metric}`);
  }
});

test("the promtool suite covers every alert added for issue #130", async () => {
  const testFile = await readFile(ALERT_TEST, "utf8");
  for (const alert of [
    "AwapWorkflowFailureRateHigh",
    "AwapNotificationRetryLagHigh",
    "AwapWebhookDeadGrowth",
    "AwapOutboxBacklogStuck",
  ]) {
    assert.ok(testFile.includes(`alertname: ${alert}`), `promtool suite misses ${alert}`);
    assert.ok(testFile.includes(`alertname: ${alert}\n        exp_alerts: []`), `${alert} lacks a negative case`);
  }
});

test("every metric referenced by the alert rules is catalogued", async () => {
  const catalog = new Set(
    (await loadJson(CATALOG)).metrics.map((entry) => metricBase(entry.name)),
  );
  const rules = await readFile(new URL("../alert-rules.yml", import.meta.url), "utf8");
  const blocks = rules
    .split(/\n(?=      - alert: )/)
    .filter((block) => block.includes("- alert: "));
  const missing = [];
  for (const block of blocks) {
    const expr = block.split("expr:")[1]?.split("for:")[0] ?? "";
    for (const token of metricTokens(expr)) {
      if (!catalog.has(metricBase(token))) {
        missing.push(token);
      }
    }
  }
  assert.deepEqual(missing, [], `uncatalogued alert metrics: ${missing.join(", ")}`);
});
